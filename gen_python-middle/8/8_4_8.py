"""
На вход программе подается строка, состоящая из трех слов. Верно ли, что для записи всех трех слов был использован
один и тот же набор букв?
Формат входных данных
На вход программе подается строка, состоящая из трех слов.
Формат выходных данных
Программа должна вывести YES, если для записи всех трех слов был использован один и тот же набор букв, или NO в противном случае.
"""

l = [set(i) for i in input().split()]
print("YES" if all(l[0] == i for i in l[1:]) else "NO")

